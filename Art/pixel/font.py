def build(out_png, out_json):
    chars = sorted(G.keys())
    W = sum(len(G[c][0]) + 1 for c in chars)
    img = np.zeros((H, W, 4), np.uint8)
    meta = {"height": H, "baseline": 7, "line": 11, "space": 1, "glyphs": []}
    x = 0
    for c in chars:
        rows = G[c]
        w = len(rows[0])
        for y, r in enumerate(rows):
            for i, ch in enumerate(r):
                if ch == '#':
                    img[y, x + i] = (255, 255, 255, 255)
        meta["glyphs"].append({"c": ord(c), "x": x, "w": w})
        x += w + 1
    Image.fromarray(img).save(out_png)
    json.dump(meta, open(out_json, "w"))
    print("font", len(chars), "glyphs", W, "px wide")


