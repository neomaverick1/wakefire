H = 9          # rows 0..6 sit on the baseline, 7..8 are descenders
G = {}


def g(ch, *rows):
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, '.') for r in rows] + ['.' * w] * (H - len(rows))
    G[ch] = rows


